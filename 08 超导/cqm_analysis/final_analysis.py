"""
最终分析：arccoth形式是否根本无法前向预言？

核心问题：
  Tc = θ_D / ln(2λ/ε), ε = λ + βδ_v - 1
  λ ≈ 0.018, βδ_v ≈ 0.982, ε ≈ 10⁻¹⁵

  要精确计算ε = λ + βδ_v - 1，需要λ和βδ_v精度 ~ 10⁻¹⁵
  任何前向方法都达不到。

  但如果换一种参数化，直接计算λ_eff = x-1呢？
  λ_eff = (λ - 1 + βδ_v) / (1 - βδ_v)
  分子 = λ - 1 + βδ_v ≈ 10⁻¹⁵（两个接近1的量的差）
  仍然需要高精度。

  结论：arccoth形式固有地需要高精度，无法前向预言。

  出路：修改Tc公式形式
"""

import numpy as np
from mpmath import mp, mpf, log, exp, tanh, atanh, coth

mp.dps = 50

BETA = 8 * mp.pi + 1
GAP = mpf("21.022040") - mpf("14.134725")

print("=" * 90)
print("最终分析：arccoth形式的根本困难")
print("=" * 90)

# 核心数值（从Nb反推：θ_D=275K, Tc=9.2K）
# Tc = θ_D / (2·arccoth(x)), x = 3β²Δδ₀²/(16(1-βδ_v)·GAP)
# 反推: δ_v ≈ 0.03758, βδ_v ≈ 0.9819
# 取 λ = 3β²Δδ₀²/(16·GAP) ≈ 0.018 (从晶格), βδ_v = 0.9819
theta_D = mpf("275")
Tc_exp = mpf("9.2")
# 反推x: 2·arccoth(x) = θ_D/Tc → x = coth(θ_D/(2Tc))
x_rev = coth(theta_D / (2 * Tc_exp))
print(f"\nNb反推参数:")
print(f"  θ_D = {theta_D}K, Tc_exp = {Tc_exp}K")
print(f"  x_rev = coth(θ_D/(2Tc)) = {float(x_rev):.6f}")

# 拆分x: x = λ/(1-βδ_v), 取 λ=0.018, 则 1-βδ_v = λ/x
lam = mpf("0.018")
one_minus_beta_dv = lam / x_rev
beta_dv = 1 - one_minus_beta_dv
eps = lam - one_minus_beta_dv  # = λ - (1-βδ_v) = λ + βδ_v - 1

print(f"\nNb的参数分解:")
print(f"  λ = {lam}")
print(f"  βδ_v = {float(beta_dv):.8f}")
print(f"  1 - βδ_v = {float(one_minus_beta_dv):.8f}")
print(f"  ε = λ - (1-βδ_v) = {float(eps):.3e}")
print(f"  x = λ/(1-βδ_v) = {float(lam/one_minus_beta_dv):.6f}")
Tc_calc = theta_D / (2 * atanh(1 / (lam / one_minus_beta_dv)))
print(f"  Tc = θ_D/(2·arccoth(x)) = {float(Tc_calc):.2f}K")

# 精度需求
print(f"\n{'='*90}")
print("精度需求分析")
print(f"{'='*90}")

print(f"""
要前向计算ε = λ + βδ_v - 1:

  λ ≈ 0.018 (从晶格计算, 精度~10⁻³)
  βδ_v ≈ 0.982 (从Fermi面计算, 精度~10⁻³)
  ε ≈ 10⁻¹⁵ (两个~O(1)量的差)

  浮点减法: 0.018 + 0.982 - 1 = 0.000 (精度丢失!)

  要ε精度~10%, 需要λ和βδ_v精度~10⁻¹⁶
  双精度浮点: 15-16位有效数字
  即使用mpmath(50位), 从材料参数计算的λ和δ_v也只有~3位精度

  根本困难: λ和βδ_v各自精度~10⁻³, 但需要~10⁻¹⁵
  差距: 12个数量级!
""")

# 验证：即使知道λ精确到10位，δ_v精确到10位，ε仍不准确
print("验证：λ和δ_v各精确到N位，ε的精度:")
for n_digits in [3, 5, 8, 10, 15, 20]:
    lam_r = mpf(mp.nstr(lam, n_digits))
    dv_r = mpf(mp.nstr(beta_dv, n_digits))
    eps_r = lam_r + dv_r - 1
    eps_err = abs(eps_r - eps) / eps if eps != 0 else 0
    print(f"  {n_digits}位: λ={mp.nstr(lam_r, n_digits)}, βδ_v={mp.nstr(dv_r, n_digits)}, ε={mp.nstr(eps_r, 5)}, ε误差={float(eps_err):.1e}")

