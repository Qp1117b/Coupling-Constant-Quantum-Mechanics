# Tc计算
def Tc_formula(delta_delta_0, delta_v, beta, theta_D, gamma_1, gamma_2):
    """Tc闭式: Tc = θ_D / (2·arccoth(x))"""
    gap = gamma_2 - gamma_1
    x = 3 * beta**2 * delta_delta_0**2 / (16 * (1 - beta * delta_v) * gap)
    if x <= 1:
        return 0.0  # 不超导
    arccoth_x = 0.5 * math.log((x + 1) / (x - 1))
    return theta_D / (2 * arccoth_x)

