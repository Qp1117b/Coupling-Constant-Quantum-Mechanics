def V_angle_activation(n, delta_delta_0, delta_v, beta, T, Omega_0, theta_D):
    """角亏激活能 V_角亏激活(n,T)"""
    if n == 1:
        return 0.0
    # Δδ_v(T) = Δδ_0 · √(tanh(ℏΩ₀/(2k_BT)))
    # 用 θ_D = ℏΩ₀/k_B 简化: ℏΩ₀/(2k_BT) = θ_D/(2T)
    tanh_arg = theta_D / (2 * T) if T > 0 else float('inf')
    delta_delta_T = delta_delta_0 * math.sqrt(math.tanh(tanh_arg))
    # V_角亏激活 = β²·Δδ²·(n²-1) / (4n²·(1-βδ))
    if 1 - beta * delta_v <= 0:
        return 0.0
    return beta**2 * delta_delta_T**2 * (n**2 - 1) / (4 * n**2 * (1 - beta * delta_v))

def eigenvalue_super(n, delta_delta_0, delta_v, beta, T, theta_D):
    """超导同步算符本征值 λ_n(T) = γ_n - V_角亏激活(n,T)"""
    gamma_n = gamma_zeros[n-1] if n <= len(gamma_zeros) else gamma_zeros[-1]
    return gamma_n - V_angle_activation(n, delta_delta_0, delta_v, beta, T, 0, theta_D)

