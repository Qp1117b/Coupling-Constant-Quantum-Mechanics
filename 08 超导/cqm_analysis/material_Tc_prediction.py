"""
具体材料Tc数值预测

从Tc闭式:
  Tc = θ_D / (2·arccoth(x))
  x = 3β²Δδ₀² / (16(1-βδ_v)(γ₂-γ₁))

反问题: 给定实验Tc和θ_D，计算所需Δδ₀
  x = coth(θ_D / (2Tc))
  Δδ₀ = √(16(1-βδ_v)(γ₂-γ₁)x / (3β²))

正问题: 给定材料结构参数(δ_v, Δδ₀, θ_D)，预测Tc
"""

import math
