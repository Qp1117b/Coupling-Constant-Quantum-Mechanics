# 基本常数
beta = 8 * math.pi + 1  # β = 8π+1
gamma_1 = 14.134725
gamma_2 = 21.022040
gap = gamma_2 - gamma_1  # ≈ 6.89

print(f"β = 8π+1 = {beta:.4f}")
print(f"γ₁ = {gamma_1:.4f}, γ₂ = {gamma_2:.4f}, gap = {gap:.4f}")

# ============================================================
# Tc公式
# ============================================================
def Tc_from_params(delta_delta_0, delta_v, theta_D):
    """从材料参数计算Tc"""
    x = 3 * beta**2 * delta_delta_0**2 / (16 * (1 - beta * delta_v) * gap)
    if x <= 1:
        return 0.0
    arccoth_x = 0.5 * math.log((x + 1) / (x - 1))
    return theta_D / (2 * arccoth_x)

def ddv0_from_Tc(Tc, delta_v, theta_D):
    """从实验Tc反推Δδ₀"""
    if Tc <= 0:
        return 0.0
    arccoth_val = theta_D / (2 * Tc)
    x = 1.0 / math.tanh(arccoth_val)  # coth = 1/tanh
    ddv0_sq = 16 * (1 - beta * delta_v) * gap * x / (3 * beta**2)
    return math.sqrt(ddv0_sq)

def x_from_Tc(Tc, theta_D):
    """从Tc计算x"""
    arccoth_val = theta_D / (2 * Tc)
    return 1.0 / math.tanh(arccoth_val)

