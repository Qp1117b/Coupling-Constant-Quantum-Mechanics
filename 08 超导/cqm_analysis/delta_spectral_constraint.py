def A4_cartan():
    """A_4 型嘉当矩阵 (SU(5) 的嘉当矩阵)"""
    return np.array([
        [ 2, -1,  0,  0],
        [-1,  2, -1,  0],
        [ 0, -1,  2, -1],
        [ 0,  0, -1,  2]
    ], dtype=float)

def D_delta(delta):
    """D(δ) = A_4 + (1-δ)·Δ, Δ 仅在 (3,4)/(4,3) 位置"""
    D = A4_cartan().copy()
    D[2, 3] = -delta  # 0-indexed: (3,4) → (2,3)
    D[3, 2] = -delta
    return D

